#pragma once
#include <stdint.h>

/* Keep the exact 8-byte wire layout on both GCC and the MSVC host tests. */
#if defined(_MSC_VER)
#pragma pack(push,1)
typedef struct {
    uint16_t buttons;
    uint8_t hat;
    uint8_t lx, ly, rx, ry;
    uint8_t vendor;
} SwitchGamepadReport;
#pragma pack(pop)
#else
typedef struct __attribute__((packed)) {
    uint16_t buttons;
    uint8_t hat;
    uint8_t lx, ly, rx, ry;
    uint8_t vendor;
} SwitchGamepadReport;
#endif

#define SWITCH_GAMEPAD_A              0x0004
#define SWITCH_GAMEPAD_NEUTRAL        0x0000
#define SWITCH_GAMEPAD_HAT_NONE       0x08
#define SWITCH_GAMEPAD_STICK_CENTER   0x80

_Static_assert(sizeof(SwitchGamepadReport) == 8,
    "Switch gamepad report must be 8 bytes");

/* PicoSwitch gamepad HID report descriptor. */
